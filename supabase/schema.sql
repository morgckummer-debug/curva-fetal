-- ── Função utilitária: mantém updated_at sempre atualizado ──
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ═══════════════════════════════════════════════════════════════════════
-- PATIENTS
-- ═══════════════════════════════════════════════════════════════════════
create table if not exists public.patients (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null default auth.uid() references auth.users(id) on delete cascade,
  cpf          text not null,
  nome         text not null default '',
  excluido_em  timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists patients_user_id_idx on public.patients(user_id);
create index if not exists patients_cpf_idx      on public.patients(user_id, cpf);

drop trigger if exists set_updated_at on public.patients;
create trigger set_updated_at
  before update on public.patients
  for each row execute function public.set_updated_at();

alter table public.patients enable row level security;

drop policy if exists "patients: dono pode tudo" on public.patients;
create policy "patients: dono pode tudo"
  on public.patients
  for all
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- ═══════════════════════════════════════════════════════════════════════
-- GESTACOES
-- ═══════════════════════════════════════════════════════════════════════
create table if not exists public.gestacoes (
  id                        bigint generated by default as identity primary key,
  user_id                   uuid not null default auth.uid() references auth.users(id) on delete cascade,
  paciente_id               bigint not null references public.patients(id) on delete cascade,
  dum                       date,
  dpp                       date,
  data_inicio               date,
  gestas                    integer,
  partos                    integer,
  abortos                   integer,
  antecedentes_obstetricos  text not null default '',
  status                    text not null default 'ativa'
                              check (status in ('ativa','finalizada','aborto','ectopica','obito_fetal')),
  observacoes               text not null default '',
  ig_base_data              date,
  ig_base_valor             integer,
  ig_base_tipo              text check (ig_base_tipo in ('DUM','US')),
  tipo_gestacao             text not null default 'unica'
                              check (tipo_gestacao in ('unica','gemelar')),
  corionicidade             text
                              check (corionicidade in ('dicorionica_diamniotica','monocorionica_diamniotica','monocorionica_monoamniotica')),
  excluido_em               timestamptz,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now()
);

create index if not exists gestacoes_user_id_idx     on public.gestacoes(user_id);
create index if not exists gestacoes_paciente_id_idx on public.gestacoes(paciente_id);

drop trigger if exists set_updated_at on public.gestacoes;
create trigger set_updated_at
  before update on public.gestacoes
  for each row execute function public.set_updated_at();

alter table public.gestacoes enable row level security;

drop policy if exists "gestacoes: dono pode tudo" on public.gestacoes;
create policy "gestacoes: dono pode tudo"
  on public.gestacoes
  for all
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

