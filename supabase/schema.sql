--
-- O que isso cria:
--   - 3 tabelas: patients, gestacoes, exams (mesmos campos que o app já usa)
--   - Row Level Security (RLS) em todas: cada linha só é visível/editável
--     por quem a criou (auth.uid()) — mesmo com a chave pública anon,
--     ninguém enxerga dado de outro usuário.
--   - created_at / updated_at automáticos, como início de trilha de
--     auditoria (quem mexeu por último e quando).
--   - id "generated by default as identity": o app escolhe o próprio id
--     (contador interno, igual sempre funcionou) em vez de esperar o banco
--     gerar — banco só gera sozinho se o app não mandar nenhum.
--
-- Já rodou este arquivo antes (versão com "generated always as identity")?
-- Não precisa rodar tudo de novo — vá direto no supabase/migrations/
-- 001_identity_by_default.sql, que só ajusta essa parte.
